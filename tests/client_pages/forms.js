(async () => {
  const out = {};
  const tick = (ms = 40) => new Promise((r) => setTimeout(r, ms));
  const $ = (s) => document.querySelector(s);
  const text = (s) => ($(s) ? $(s).textContent.trim() : null);
  const click = async (s) => { $(s).click(); await tick(); };
  try {
    $("#boot").click();
    for (let i = 0; i < 300 && !window.__quillo_booted; i++) await tick(30);
    await tick(100);
    out.late = text("#late");
    await click("#late");
    out.lateAfter = text("#late");
    await click("#late");
    out.earlyAfter = text("#early");
    out.lateGone = !$("#late");
    out.tried = text("#tried");
    await click("#tried");
    out.triedAfter = text("#tried");
    out.counted = text("#counted");
    await click("#counted");
    out.countedAfter = text("#counted");
    out.parts = text("#parts");
    await click("#parts");
    out.partsAfter = text("#parts");
    await click("#showattrs");
    out.flag = text("#flag");
    out.bare = $("#bare").checked;
    out.noclass = $("#noclass").className;
    out.inblock = text("#inblock");
    out.guarded = text("#guarded");
    await click("#guarded");
    out.guardedAfter = text("#guarded");
    out.rows = [...document.querySelectorAll("#rows li")].length;
    await click("#addrow");
    out.rowsAfter = [...document.querySelectorAll("#rows li")].map((l) => l.className + ":" + l.textContent.replace(/\s+/g, ""));
    out.counts = [...document.querySelectorAll("#rows li")].map((l) => l.title + "." + l.lang);
    out.titles = [...document.querySelectorAll("#rows span")].map((s) => s.title + "." + s.className);
    out.nested = [...document.querySelectorAll("#rows em")].map((e) => e.className + "." + e.title + "." + e.textContent.trim());
    await click("#showcalls");
    out.fieldfn = text("#fieldfn");
    out.propfn = text("#propfn");
    out.localfn = text("#localfn");
    out.itemfn = text("#itemfn");
    await click("#letcalls");
    out.letcalls = text("#letcalls");
    out.errors = window.__quilloErrors || [];
  } catch (e) { out.exception = String(e && e.stack || e); }
  document.body.setAttribute("data-result", JSON.stringify(out));
})();
