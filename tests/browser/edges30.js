// feedback27-35-fixes).
(async () => {
  const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
  const $ = (id) => document.getElementById(id);
  const click = async (id, ms = 80) => { $(id).click(); await sleep(ms); };
  const out = {};
  await sleep(150);
  await click("facts", 150);
  out.server = JSON.parse($("server").textContent);
  out.browser = JSON.parse($("browser").textContent);
  const k = $("keys");
  k.dispatchEvent(new KeyboardEvent("keydown", { key: "x", bubbles: true }));
  k.dispatchEvent(new KeyboardEvent("keydown", { key: "x", bubbles: true }));
  await sleep(80);
  out.keys = k.textContent;
  await click("sums");
  out.sums = [$("sums-render").textContent, $("sums").textContent];
  await click("show");
  out.child = $("child") && $("child").textContent;
  await click("rec", 150);
  out.rec = $("rec").textContent;
  await click("clear");
  out.due = $("due").textContent;
  out.copy = $("copy").children.length;
  await click("more");
  out.copy_more = $("copy").children.length;
  const st = $("styled");
  out.style = [getComputedStyle(st).color, st.style.fontSize, st.style.marginTop];
  st.click();
  await sleep(60);
  out.style.push(getComputedStyle(st).color);
  out.scripted = [window.__scripted, window.__said];
  $("ask").click();
  await sleep(80);
  const ok = document.querySelector(".q-ok"), cancel = document.querySelector(".q-cancel");
  out.ask = [ok && ok.textContent, cancel && cancel.textContent];
  if (cancel) cancel.click();
  await sleep(80);
  out.ask.push($("ask").textContent);
  const dt = new DataTransfer();
  dt.items.add(new File(["xray"], "xray.png", { type: "image/png" }));
  dt.items.add(new File(["notes!"], "notes \"v2\".txt", { type: "text/plain" }));
  const input = $("files");
  input.files = dt.files;
  input.dispatchEvent(new Event("change", { bubbles: true }));
  await sleep(400);
  out.up = JSON.parse($("up").textContent);
  const box = $("box");
  box.focus();
  box.click();
  await sleep(80);
  out.tick = [$("box") === box, document.activeElement === box, box.checked, box.parentNode.textContent];
  box.click();
  await sleep(80);
  out.tick.push($("box") === box, box.checked, box.parentNode.textContent);
  const field = $("field");
  field.focus();
  field.value = "ab";
  field.dispatchEvent(new Event("input", { bubbles: true }));
  await sleep(80);
  out.field = [$("field") === field, document.activeElement === field, $("typed").textContent];
  const before = (window.__quilloErrors || []).length;
  for (let i = 1; i <= 10; i++) await click("f" + i, 30);
  out.fails = (window.__quilloErrors || []).slice(before);
  await click("away", 600);
  out.away = $("away").textContent;
  await sleep(200);
  await click("pic-go", 150);
  out.pic = $("pic-seen").textContent;
  out.remade = window.__quilloRemade || 0;
  out.errors = (window.__quilloErrors || []).slice(0, before);
  document.body.setAttribute("data-result", JSON.stringify(out));
})();
