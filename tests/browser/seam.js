// Drives the page's seams, and reads what each left.
(async () => {
  const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
  const $ = (id) => document.getElementById(id);
  const click = async (id, ms = 60) => { $(id).click(); await sleep(ms); };
  const out = {};
  await sleep(100);
  out.same = $("same").textContent;
  await click("prop", 200);
  await click("prop-plain", 60);
  out.prop = $("prop-out").textContent;
  out.prop_plain = $("prop-plain-out").textContent;
  await click("late");
  out.late = [location.hash, $("late").textContent];
  await click("has");
  out.has = JSON.parse($("has").textContent);
  const box = $("box");
  await click("hand");
  out.hand = [box.style.transform, box.classList.contains("hand")];
  await click("same-text");
  out.same_text = [box.style.transform, box.classList.contains("hand")];
  await click("new-text");
  out.new_text = [box.style.transform, box.style.getPropertyValue("--a").trim(), box.style.color, box.classList.contains("hand")];
  await click("flip");
  out.flip = [box.classList.contains("on"), box.classList.contains("off"), box.classList.contains("hand"), box.style.transform];
  const v = $("v");
  out.muted = [v.muted];
  await click("unmute");
  out.muted.push(v.muted);
  await click("unmute");
  out.muted.push(v.muted);
  const d = $("d");
  d.open = false;
  await click("other");
  out.closed_stays = d.open;
  const rows = () => [...$("rows").children].map((x) => x.textContent);
  await click("flip-rows");
  await click("empty");
  out.empty_after_flip = rows();
  await click("fill");
  out.fill = rows();
  await click("flip-rows");
  await click("flip-rows");
  await click("empty");
  out.flip_twice = rows();
  await click("cursor");
  out.cursor = JSON.parse($("cursor").textContent);
  await click("after", 90);
  out.after = $("later").textContent;
  await click("tick");
  out.tick = $("later").textContent;
  await click("show", 10);
  await click("click-timer", 10);
  await click("gone", 120);
  out.gone = $("gone-out").textContent;
  window.__slow = { get: () => new Promise((r) => setTimeout(() => r("done"), 20)) };
  await click("waits", 120);
  out.waits = $("waits-out").textContent;
  await click("then");
  out.then = $("then-out").textContent;
  await click("kept");
  out.kept = $("kept-out").textContent;
  out.bare = $("bare").textContent;
  await click("ticker", 80);
  const ticking = Number($("ticks").textContent);
  await click("ticks-stop", 20);
  const stopped = Number($("ticks").textContent);
  await sleep(80);
  out.ticks = [ticking > 2, Number($("ticks").textContent) - stopped];
  out.errors = window.__quilloErrors || [];
  document.body.setAttribute("data-result", JSON.stringify(out));
})();
